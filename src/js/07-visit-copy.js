function visitStableIndex(seed, length){
  var text = String(seed || ''), hash = 2166136261;
  for (var i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash) % Math.max(1, length);
}

function visitCopyFor(total, today){
  total = Math.max(0, Number(total) || 0);
  today = Math.max(0, Number(today) || 0);
  var seed = wTodayStr() + '|' + total + '|' + today;
  var special = VISIT_X_SPECIAL[String(total)];
  if (special) return { text: special, special: true };
  if (VISIT_Y_COPY[today]) {
    var yLines = VISIT_Y_COPY[today];
    return { text: yLines[visitStableIndex(seed, yLines.length)], special: false };
  }
  if (today > 20) {
    var fallbackY = VISIT_Y_FALLBACK[visitStableIndex(seed, VISIT_Y_FALLBACK.length)];
    return { text: fallbackY.replace('{y}', String(today)), special: false };
  }
  return {
    text: VISIT_X_FALLBACK[visitStableIndex(seed, VISIT_X_FALLBACK.length)],
    special: false
  };
}
